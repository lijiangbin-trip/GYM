  const supportedLanguages = Object.keys(copy);

  function setLanguage(language) {
    const selectedLanguage = supportedLanguages.includes(language) ? language : 'ja';
    const dictionary = copy[selectedLanguage];

    document.documentElement.lang = selectedLanguage === 'zh' ? 'zh-CN' : selectedLanguage;
    document.querySelectorAll('[data-i18n]').forEach((element) => {
      const value = dictionary[element.dataset.i18n];
      if (value !== undefined) element.innerHTML = value;
    });
    document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
      const value = dictionary[element.dataset.i18nAlt];
      if (value !== undefined) element.alt = value;
    });
    document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
      const value = dictionary[element.dataset.i18nAria];
      if (value !== undefined) element.setAttribute('aria-label', value);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
      const value = dictionary[element.dataset.i18nPlaceholder];
      if (value !== undefined) element.setAttribute('placeholder', value);
    });

    options.forEach((option) => {
      const isSelected = option.dataset.language === selectedLanguage;
      option.setAttribute('aria-checked', String(isSelected));
    });
    try {
      localStorage.setItem('dir-coach-language', selectedLanguage);
    } catch (error) {
      console.warn('Language preference could not be saved for this browser session.', error);
    }
    document.dispatchEvent(new CustomEvent('site-language-change', { detail: { language: selectedLanguage } }));
  }

